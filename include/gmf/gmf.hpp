// Generalized maximum flow (maximum flow with gains / lossy networks).
//
// Each arc (u, v) carries a capacity c and a multiplier g > 0: pushing x units
// into the arc at u consumes x units of capacity and delivers g * x units at v.
// The solver maximises the amount delivered at the sink.
//
// The method is Onaga's highest-gain augmenting path algorithm, run with node
// potentials so each augmentation costs one early-exit Dijkstra rather than a
// full label-correcting sweep, extended with cancellation of flow-generating
// cycles so that gain-amplifying inputs are handled too. See docs/ALGORITHM.md
// for the derivation and the optimality certificate every result carries.
#pragma once

#include <cstddef>
#include <string>
#include <vector>

namespace gmf {

struct EdgeInput {
  int from = 0;
  int to = 0;
  double capacity = 0.0;    // units that may enter the arc at `from`
  double multiplier = 1.0;  // units delivered at `to` per unit entering
};

struct Problem {
  int num_nodes = 0;
  int source = -1;
  int sink = -1;
  std::vector<EdgeInput> edges;
  // Optional display names, indexed by node id. Empty means "use the index".
  std::vector<std::string> node_names;
};

struct Options {
  // Relative tolerance. Residual capacities below epsilon * capacity_scale are
  // treated as zero, and a gain improvement must exceed epsilon in log space to
  // count as an improvement.
  double epsilon = 1e-12;
  // 0 selects a bound derived from the problem size.
  long long max_iterations = 0;
  // 1 = sequential. >1 fans the label-correcting sweep out across that many
  // threads. 0 = use the hardware concurrency. This affects only the sweeps
  // that establish node potentials and hunt for flow-generating cycles; on a
  // network without amplifying cycles there is exactly one such sweep.
  int threads = 1;
  // Record the augmenting paths. Turning this off saves the step log, which is
  // the largest allocation on a big run.
  bool collect_paths = true;
  // Cancel flow-generating cycles (gain product > 1) that can reach the sink.
  // With this off, such an input is reported instead of solved.
  bool cancel_generating_cycles = true;
  // Use node potentials and Dijkstra for the path search. Turning this off
  // forces the label-correcting engine for every search, which is far slower
  // and is here so the two engines can be checked against each other.
  bool use_potentials = true;
};

// One traversal of one residual arc inside an augmentation. Only what cannot be
// derived is stored: on a large run the step log dominates memory, so the
// endpoints, the multiplier and the delivered amount are recovered from the
// problem with the helpers below.
struct Step {
  int edge = -1;        // index into Problem::edges
  bool forward = true;  // false = traversed backwards, undoing earlier flow
  double flow_in = 0.0; // units entering this residual arc
};

inline int step_from(const Problem& problem, const Step& step) {
  const EdgeInput& edge = problem.edges[static_cast<std::size_t>(step.edge)];
  return step.forward ? edge.from : edge.to;
}

inline int step_to(const Problem& problem, const Step& step) {
  const EdgeInput& edge = problem.edges[static_cast<std::size_t>(step.edge)];
  return step.forward ? edge.to : edge.from;
}

inline double step_multiplier(const Problem& problem, const Step& step) {
  const double multiplier = problem.edges[static_cast<std::size_t>(step.edge)].multiplier;
  return step.forward ? multiplier : 1.0 / multiplier;
}

inline double step_flow_out(const Problem& problem, const Step& step) {
  return step.flow_in * step_multiplier(problem, step);
}

struct Augmentation {
  enum class Kind {
    Path,            // a residual source -> sink path
    GeneratingCycle  // a flow-generating cycle plus the route carrying its excess
  };

  Kind kind = Kind::Path;
  // This augmentation's slice of Result::steps. The steps of all augmentations
  // live in one array rather than a vector each.
  std::size_t step_begin = 0;
  std::size_t step_count = 0;
  std::size_t cycle_length = 0;  // steps belonging to the cycle itself
  double flow_in = 0.0;          // units injected at the first step
  double flow_out = 0.0;         // units delivered at the sink
  double gain = 1.0;             // product of the multipliers along the walk
  double excess = 0.0;           // units generated by the cycle, cycle kinds only
  // The arc that limited this augmentation: the constricting edge.
  int bottleneck_edge = -1;
  bool bottleneck_forward = true;
  std::size_t bottleneck_step = 0;  // offset within this augmentation's steps
};

struct Certificate {
  // Both true means the flow is optimal: no residual augmenting path, and no
  // flow-generating cycle that can reach the sink.
  bool no_augmenting_path = false;
  bool no_generating_cycle_reaching_sink = false;
  double max_conservation_error = 0.0;
  double max_capacity_violation = 0.0;
};

struct Stats {
  long long iterations = 0;
  long long path_searches = 0;
  long long cycle_searches = 0;
  long long relaxations = 0;
  long long parallel_fallbacks = 0;
  int threads_used = 1;

  // Which engine answered the path searches. Dijkstra needs valid node
  // potentials; a label-correcting sweep establishes or repairs them.
  long long dijkstra_searches = 0;
  long long label_correcting_searches = 0;
  long long potential_repairs = 0;
  long long heap_pops = 0;
  long long blocked_arcs = 0;
  long long cycle_extract_failures = 0;

  // Wall-clock seconds, so the dominant phase is visible rather than guessed.
  double seconds = 0.0;
  double path_search_seconds = 0.0;
  double cycle_search_seconds = 0.0;
  double push_seconds = 0.0;

  // Bytes held by the solver's own arrays, excluding the step log.
  std::size_t working_bytes = 0;
};

struct Result {
  // "optimal", "unbounded", "iteration_limit", "suboptimal",
  // "generating_cycle_rejected" or "invalid_input".
  std::string status = "optimal";
  std::string message;
  bool optimal = false;

  double max_flow = 0.0;        // delivered at the sink
  double source_outflow = 0.0;  // injected at the source

  // Per input edge, the units entering it; delivered = flow * multiplier.
  std::vector<double> edge_flow;
  std::vector<Augmentation> augmentations;
  std::vector<Step> steps;  // indexed by Augmentation::step_begin
  Certificate certificate;
  Stats stats;
};

// Throws std::invalid_argument when the problem itself is malformed (bad node
// ids, negative capacity, non-positive multiplier).
Result solve(const Problem& problem, const Options& options = Options());

// JSON front door. Never throws: malformed input comes back as a JSON document
// with "status": "invalid_input" and an "error" field.
std::string solve_json(const std::string& request);

const char* version();

}  // namespace gmf
